#!/usr/bin/env python3
"""Import official data from Dreame app plugins (unpacked React Native bundles).

The app's plugin is the official source; the Tasshack tables are used only where it has nothing.
Writes agent/official.go (property names, fault texts) and marks the source of every entry in
agent/ui/settings.js ("src": "plugin" or "tasshack").

Usage: python3 -I tools/import_plugin_spec.py <plugin-research dir>
The dir holds unpacked/<model>/**/*.bundle as downloaded from /dreame-product/upgrades/appplugin.
"""
import glob
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# The X50 (r2505) ships the same bundle as r2489; newer common plugins fill what it lacks.
MODELS = ["r2489", "r2401", "r2513", "r2527", "r9419", "r2507"]
# Settings that need hardware the firmware's own table (dconf_runtime.json) must report.
# The app shows them only with supportLDSUp; the firmware answers them even without a lifting LDS.
HARDWARE = {(28, 3): {"LIFT_LDS": "True"}, (28, 4): {"LIFT_LDS": "True"}, (28, 51): {"LIFT_LDS": "True"}}


def bundle(src, model):
    paths = glob.glob(os.path.join(src, "unpacked", model, "**", "*.bundle"), recursive=True)
    if not paths:
        sys.exit(f"no bundle for {model} under {src}")
    with open(paths[0], encoding="utf8", errors="replace") as f:
        return f.read()


def props(text):
    """{(siid, piid): name} from the plugin's device service classes."""
    names = dict(re.findall(r"^\s+(Prop\w+): '([^']+)',", text, re.M))
    token = re.compile(r"_callSuper\(this, \w+\)|_this\.SIID = (\d+);|_this\.PIID\[_Common\.Props\.(Prop\w+)\] = (\d+);")
    out, siid = {}, None
    for m in token.finditer(text):
        if m.group(0).startswith("_callSuper"):
            siid = None
        elif m.group(1):
            siid = int(m.group(1))
        elif siid:
            out[(siid, int(m.group(3)))] = names.get(m.group(2), m.group(2))
    return out


def module(text, name):
    end = text.index('},"' + name + '",[')
    return text[text.rindex("__d(function", 0, end):end]


def strings(text, lang):
    body = module(text, f"projects_dreame.vacuum.common_src_resources_string_{lang}on")
    pairs = re.findall(r'^\s+"?([A-Za-z0-9_]+)"?: "((?:[^"\\]|\\.)*)",?$', body, re.M)
    return {k: json.loads('"' + v + '"') for k, v in pairs}


def faults(text):
    """{code: (ru, en)} titles of the app's warning dialogs (getWarnInfos)."""
    ru, en = strings(text, "ru"), strings(text, "en")
    start = text.index("var warnInfo = {", text.index("function getWarnInfos()"))
    block = text[start:text.index("\n    };", start)]
    out = {}
    for code, title in re.findall(r"'(\d+)': \{\s*'title': ([^,\n]+),", block):
        key = re.sub(r"^_string\.default\.", "", title.strip())
        if ru.get(key) or en.get(key):
            out[int(code)] = (ru.get(key, ""), en.get(key, ""))
    return out


def go_string(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    texts = {m: bundle(sys.argv[1], m) for m in MODELS}
    all_props, all_faults = {}, {}
    for m in reversed(MODELS):  # first model wins: its names and texts are the X50's
        all_props.update(props(texts[m]))
        all_faults.update(faults(texts[m]))
    with open(os.path.join(ROOT, "agent", "official.go"), "w", encoding="utf8", newline="\n") as f:
        f.write("// Code generated by tools/import_plugin_spec.py from the Dreame app plugins; DO NOT EDIT.\n\n")
        f.write("package main\n\n")
        f.write("// officialProps names every property the app plugins read, by siid/piid.\n")
        f.write("var officialProps = map[[2]int]string{\n")
        for (s, p), n in sorted(all_props.items()):
            f.write(f"\t{{{s}, {p}}}: {go_string(n)},\n")
        f.write("}\n\n")
        f.write("// officialFaults are the app's titles for 2/2 codes: Russian, English.\n")
        f.write("var officialFaults = map[int64][2]string{\n")
        for code, (ru, en) in sorted(all_faults.items()):
            f.write(f"\t{code}: {{{go_string(ru)}, {go_string(en)}}},\n")
        f.write("}\n")
    gofmt = shutil.which("gofmt")
    if gofmt:
        subprocess.run([gofmt, "-w", os.path.join(ROOT, "agent", "official.go")], check=True)
    else:
        print("gofmt not found: run gofmt -w agent/official.go before committing")

    path =os.path.join(ROOT, "agent", "ui", "settings.js")
    with open(path, encoding="utf8", newline="") as f:
        lines = f.read().split("\r\n")
    body = lines[1]
    defs = json.loads(body[body.index("["):body.rindex("]") + 1])
    joined = "\n".join(texts.values())
    for d in defs:
        key = d.get("auto") or d.get("json_key")
        official = (d["siid"], d["piid"]) in all_props and (not key or f"'{key}'" in joined or f'"{key}"' in joined)
        d["src"] = "plugin" if official else "tasshack"
        hw = HARDWARE.get((d["siid"], d["piid"]))
        if hw:
            d["hw"] = hw
    lines[0] = ("// Settings: siid/piid and keys checked against the Dreame app plugins (\"src\":\"plugin\"); "
                "the rest come from the MIT Tasshack tables (\"src\":\"tasshack\"). Labels are ours. "
                "Regenerate with tools/import_plugin_spec.py.")
    lines[1] = body[:body.index("[")] + json.dumps(defs, ensure_ascii=False, separators=(",", ":")) + body[body.rindex("]") + 1:]
    with open(path, "w", encoding="utf8", newline="") as f:
        f.write("\r\n".join(lines))
    plugin = sum(d["src"] == "plugin" for d in defs)
    print(f"{len(all_props)} properties, {len(all_faults)} fault texts, settings: {plugin} plugin, {len(defs) - plugin} tasshack")


if __name__ == "__main__":
    main()
